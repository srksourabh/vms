#!/usr/bin/env node
/**
 * After `npx supabase start`, write/refresh the three keys the SPA needs
 * so a first-run on a mall server does not copy placeholder .env.example values.
 */
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const raw = execSync('npx supabase status -o env', { encoding: 'utf8' });
const got = {};
for (const line of raw.split('\n')) {
  const i = line.indexOf('=');
  if (i < 1) continue;
  got[line.slice(0, i)] = line.slice(i + 1).replace(/^"|"$/g, '');
}
if (!got.API_URL || !got.ANON_KEY || !got.SERVICE_ROLE_KEY) {
  console.error('supabase status did not print API_URL / ANON_KEY / SERVICE_ROLE_KEY');
  process.exit(1);
}

const patch = {
  VITE_SUPABASE_URL: got.API_URL,
  VITE_SUPABASE_ANON_KEY: got.ANON_KEY,
  SUPABASE_SERVICE_ROLE_KEY: got.SERVICE_ROLE_KEY,
};

let text = existsSync('.env') ? readFileSync('.env', 'utf8') : '';
if (!text.trim()) {
  text = `# Local on-prem keys — generated by scripts/write-local-env.mjs
# Do not commit this file.
SMTP_HOST=127.0.0.1
SMTP_PORT=54325
MAIL_FROM=Secure Gate <noreply@localhost>
`;
}
for (const [k, v] of Object.entries(patch)) {
  const line = `${k}=${v}`;
  const re = new RegExp(`^${k}=.*$`, 'm');
  text = re.test(text) ? text.replace(re, line) : `${text.trimEnd()}\n${line}\n`;
}
writeFileSync('.env', text.endsWith('\n') ? text : `${text}\n`);
console.log('Wrote local keys to .env (VITE_SUPABASE_URL =', got.API_URL, ')');
